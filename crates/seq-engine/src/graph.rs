//! `Project` → `PlaybackGraph`: a flat, sorted structure ready for playback.
//! Compiled on the UI side on every edit, then sent to the engine.

use seq_model::*;
use std::collections::HashMap;

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct ChannelParams {
    pub id: ChannelId,
    pub volume: f32,
    pub pan: f32,
    pub mute: bool,
    pub solo: bool,
    pub choke: u8,
    /// `Some(midi_channel)` for a MIDI out channel.
    pub midi_channel: Option<u8>,
    /// Index of the MIDI output (`Project::midi_outs`).
    pub midi_port: u8,
    pub arp: ArpParams,
}

impl ChannelParams {
    pub fn silent(id: ChannelId) -> Self {
        ChannelParams {
            id,
            volume: 0.0,
            pan: 0.0,
            mute: true,
            solo: false,
            choke: 0,
            midi_channel: None,
            midi_port: 0,
            arp: ArpParams::default(),
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CompiledEvent {
    /// Tick within the pattern, swing applied.
    pub tick: Tick,
    /// Index into `PlaybackGraph::channels`.
    pub channel: u16,
    pub key: u8,
    pub vel: u8,
    /// Length (already truncated to the end of the pattern). The note-off is generated by the engine.
    pub len: Tick,
}

#[derive(Debug, Clone, PartialEq)]
pub struct CompiledPattern {
    pub id: PatternId,
    pub length: Tick,
    /// Sorted by tick.
    pub events: Vec<CompiledEvent>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub struct CompiledClip {
    /// Index into `PlaybackGraph::patterns`.
    pub pattern: u16,
    pub start: Tick,
    pub len: Tick,
}

#[derive(Debug, Clone, PartialEq)]
pub struct PlaybackGraph {
    pub tempo_bpm: f64,
    pub beat_len: Tick,
    pub beats_per_bar: u32,
    pub channels: Vec<ChannelParams>,
    pub patterns: Vec<CompiledPattern>,
    /// Sorted by start.
    pub song: Vec<CompiledClip>,
    pub song_length: Tick,
}

impl PlaybackGraph {
    pub fn pattern_index(&self, id: PatternId) -> Option<usize> {
        self.patterns.iter().position(|p| p.id == id)
    }
}

/// Swing offset: odd steps (sixteenth notes) are delayed by `swing * STEP / 2`.
/// Applies to any note that **starts** in an odd step, including off-grid notes.
pub fn swing_offset(start: Tick, swing: f32) -> Tick {
    if (start / STEP) % 2 == 1 {
        (swing.clamp(0.0, 1.0) * STEP as f32 / 2.0) as Tick
    } else {
        0
    }
}

pub fn compile(p: &Project) -> PlaybackGraph {
    let channels: Vec<ChannelParams> = p
        .channels
        .iter()
        .take(MAX_CHANNELS)
        .map(|c| ChannelParams {
            id: c.id,
            volume: c.volume,
            pan: c.pan,
            mute: c.mute,
            solo: c.solo,
            choke: c.choke,
            arp: c.arp,
            midi_channel: match c.kind {
                ChannelKind::MidiOut { channel, .. } => Some(channel.min(15)),
                _ => None,
            },
            midi_port: match c.kind {
                ChannelKind::MidiOut { out, .. } => out,
                _ => 0,
            },
        })
        .collect();
    let index: HashMap<ChannelId, u16> =
        channels.iter().enumerate().map(|(i, c)| (c.id, i as u16)).collect();

    let patterns: Vec<CompiledPattern> = p
        .patterns
        .iter()
        .map(|pat| {
            let length = pat.length.max(1);
            let mut events = Vec::new();
            for (cid, notes) in &pat.notes {
                let Some(&ci) = index.get(cid) else { continue };
                for n in notes {
                    if n.start >= length || n.velocity == 0 {
                        continue;
                    }
                    let tick = (n.start + swing_offset(n.start, p.swing)).min(length - 1);
                    let len = n.len.max(1).min(length - tick).max(1);
                    events.push(CompiledEvent { tick, channel: ci, key: n.key.min(127), vel: n.velocity.min(127), len });
                }
            }
            events.sort_by_key(|e| (e.tick, e.channel, e.key));
            CompiledPattern { id: pat.id, length, events }
        })
        .collect();

    let mut song: Vec<CompiledClip> = p
        .arrangement
        .clips
        .iter()
        .filter(|c| c.len > 0)
        .filter_map(|c| {
            let pi = patterns.iter().position(|cp| cp.id == c.pattern)?;
            Some(CompiledClip { pattern: pi as u16, start: c.start, len: c.len })
        })
        .collect();
    song.sort_by_key(|c| c.start);
    let song_length = song.iter().map(|c| c.start + c.len).max().unwrap_or(0);

    PlaybackGraph {
        tempo_bpm: p.tempo_bpm.clamp(10.0, 999.0),
        beat_len: p.beat_len().max(1),
        beats_per_bar: p.time_sig.0.max(1) as u32,
        channels,
        patterns,
        song,
        song_length,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn compile_kit() {
        let p = Project::from_kit(0);
        let g = compile(&p);
        assert_eq!(g.channels.len(), p.channels.len());
        let ev = &g.patterns[0].events;
        assert!(!ev.is_empty());
        assert!(ev.windows(2).all(|w| w[0].tick <= w[1].tick));
    }

    #[test]
    fn swing_shifts_odd_steps() {
        assert_eq!(swing_offset(0, 1.0), 0);
        assert_eq!(swing_offset(STEP, 1.0), STEP / 2);
        assert_eq!(swing_offset(STEP + 5, 0.5), STEP / 4);
        assert_eq!(swing_offset(2 * STEP, 1.0), 0);
    }

    #[test]
    fn notes_truncated_to_pattern() {
        let mut p = Project::empty();
        let ch = p.add_channel("s", ChannelKind::Synth(SynthParams::default())).unwrap();
        let pat = p.patterns[0].id;
        let len = p.pattern(pat).unwrap().length;
        p.pattern_mut(pat).unwrap().notes.insert(
            ch,
            vec![
                Note { start: len - 100, len: 1000, key: 60, velocity: 100 },
                Note { start: len + 5, len: 10, key: 60, velocity: 100 },
            ],
        );
        let g = compile(&p);
        assert_eq!(g.patterns[0].events.len(), 1);
        assert_eq!(g.patterns[0].events[0].len, 100);
    }
}
